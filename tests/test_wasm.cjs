const fs=require('fs'),vm=require('vm'),assert=require('assert');
const JSZip=require('../docs/vendor/jszip.min.js');
if(!globalThis.crypto)globalThis.crypto=require('crypto').webcrypto;
vm.runInThisContext(fs.readFileSync(__dirname+'/../docs/wasm/wasm_exec.js','utf8'));
const go=new Go();
(async()=>{
 const source=fs.readFileSync(__dirname+'/../docs/wasm/folio-import.wasm');
 const r=await WebAssembly.instantiate(source,go.importObject);
 go.run(r.instance);
 assert.equal(typeof globalThis.folioWasmImport,'function');
 const pdf=new Uint8Array(fs.readFileSync(__dirname+'/go/examples/banco-marcas.pdf'));
 const data=JSON.parse(globalThis.folioWasmImport('banco-marcas.pdf',pdf));
 if(data.error)throw Error(data.error);
 assert.ok(data.lines.length>=3,'No se extrajo texto del PDF');
 assert.ok(data.lines.some(x=>x.mark),'No se detectaron marcas vectoriales');
 const parseLines=require('../docs/import.js').parseLines;
 const questions=parseLines(data.lines);
 assert.ok(questions.length>=2,'No se detectaron preguntas');
 assert.ok(questions.some(q=>q.answer>=0),'No se detectó respuesta marcada');
 console.log('PDF WASM:',data.lines.length,'líneas,',questions.length,'preguntas');
 const zip=new JSZip();
 zip.file('word/document.xml','<?xml version="1.0"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>1. ¿Qué es el PIB?</w:t></w:r></w:p><w:p><w:r><w:rPr><w:color w:val="FF0000"/></w:rPr><w:t>A) Producto interior bruto</w:t></w:r></w:p><w:p><w:r><w:t>B) Producto impuesto bruto</w:t></w:r></w:p></w:body></w:document>');
 const docx=await zip.generateAsync({type:'uint8array'});
 const parsed=JSON.parse(globalThis.folioWasmImport('test.docx',docx));
 if(parsed.error)throw Error(parsed.error);
 assert.equal(parsed.lines.length,3);
 assert.equal(parsed.lines[1].color,true);
 const qs=parseLines(parsed.lines);
 assert.equal(qs.length,1);assert.equal(qs[0].answer,0);
 console.log('DOCX WASM:',parsed.lines.length,'párrafos, marca por color detectada');
 process.exit(0);
})().catch(err=>{console.error(err);process.exit(1)});
